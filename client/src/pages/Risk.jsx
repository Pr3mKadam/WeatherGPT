import { Link } from 'react-router-dom';
import {
  AlertTriangle,
  ArrowRight,
  Clock,
  Info,
  MapPin,
  RefreshCw,
  ShieldAlert,
  ShieldCheck,
  SlidersHorizontal,
} from 'lucide-react';
import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
  ReferenceLine,
} from 'recharts';

import PageHeader from '../components/PageHeader.jsx';
import ChartCard from '../components/ChartCard.jsx';
import DataBadge from '../components/DataBadge.jsx';
import RiskGauge from '../components/RiskGauge.jsx';
import AlertCard from '../components/AlertCard.jsx';
import EmptyState from '../components/EmptyState.jsx';
import SourceNote from '../components/SourceNote.jsx';
import ErrorState from '../components/ErrorState.jsx';
import { SkeletonCard } from '../components/Loading.jsx';
import { useApi } from '../hooks/useApi.js';
import { locationParams } from '../lib/api.js';
import { useLocation } from '../context/LocationContext.jsx';
import { formatDate, formatNumber, relativeTime, weekday } from '../lib/format.js';

function RiskTooltip({ active, payload }) {
  if (!active || !payload?.length) return null;
  const point = payload[0]?.payload;
  return (
    <div className="chart-tooltip">
      <span className="chart-tooltip-title">{point?.label}</span>
      <div className="chart-tooltip-row">
        <span className="chart-dot" style={{ background: point?.color }} />
        <span>{point?.level} risk</span>
        <strong>{formatNumber(point?.score, 0)}/100</strong>
      </div>
      <div className="chart-tooltip-sub">Weighted heuristic · estimated</div>
    </div>
  );
}

export default function Risk() {
  const { location } = useLocation();
  const path = `/risk?${locationParams(location)}`;
  const { data, loading, error, refresh } = useApi(path);

  if (loading && !data) {
    return (
      <div className="page">
        <PageHeader
          eyebrow="Environmental risk"
          title={`Risk outlook for ${location.name}`}
          description="Computing today's advisories and composite indicator…"
        />
        <div className="two-col-grid">
          <SkeletonCard height={300} lines={3} />
          <SkeletonCard height={300} lines={3} />
        </div>
      </div>
    );
  }

  if (error) {
    return (
      <div className="page">
        <PageHeader eyebrow="Environmental risk" title="Environmental risk" />
        <ErrorState title="Could not load the risk assessment" error={error} onRetry={refresh} />
      </div>
    );
  }

  const { risk, alerts } = data;
  const daily = risk.daily.map((day, index) => ({
    ...day,
    label: index === 0 ? 'Today' : index === 1 ? 'Tomorrow' : weekday(day.date),
  }));

  return (
    <div className="page">
      <PageHeader
        eyebrow="Environmental risk"
        title={`Risk outlook for ${data.location?.name || location.name}`}
        description="A transparent composite of air quality, heat, rain, wind and UV — plus the computed advisories that follow from it."
        meta={
          <>
            <span className="meta-item">
              <MapPin size={14} aria-hidden="true" />
              {[location.name, location.admin1, location.country].filter(Boolean).join(', ')}
            </span>
            <span className="meta-item">
              <Clock size={14} aria-hidden="true" />
              Computed {relativeTime(data.fetchedAt)}
            </span>
            <DataBadge
              status="estimated"
              label="Computed advisory"
              title="Generated by WeatherGPT from the forecast. Not an official IMD or CPCB warning."
            />
          </>
        }
        actions={
          <button type="button" className="btn btn-outline" onClick={refresh} disabled={loading}>
            <RefreshCw size={16} className={loading ? 'spin' : ''} />
            {loading ? 'Refreshing…' : 'Refresh'}
          </button>
        }
      />

      <div className="inline-warning">
        <AlertTriangle size={16} aria-hidden="true" />
        <span>
          These advisories are computed automatically from the forecast. They are not official IMD
          or CPCB warnings. For decisions that affect safety, check the official sources.
        </span>
      </div>

      <div className="risk-layout">
        <section className="card risk-hero-card">
          <div className="card-head">
            <div>
              <h2 className="card-title">Today's composite risk</h2>
              <p className="card-subtitle">{risk.level} risk · weighted heuristic</p>
            </div>
            <DataBadge status="estimated" label="Awareness indicator" />
          </div>

          <RiskGauge value={risk.score} level={risk.level} color={risk.color} size={240} />

          <p className="risk-hero-summary">{risk.summary}</p>

          <div className="risk-advice">
            <ShieldCheck size={17} aria-hidden="true" />
            <p>{risk.advice}</p>
          </div>
        </section>

        <section className="card">
          <div className="card-head">
            <div>
              <h2 className="card-title">What is driving the score</h2>
              <p className="card-subtitle">Each factor's normalised value and weighted contribution</p>
            </div>
            <SlidersHorizontal size={18} aria-hidden="true" />
          </div>

          <div className="risk-components">
            {risk.components.map((component) => (
              <div className={`risk-component ${component.available ? '' : 'is-unavailable'}`.trim()} key={component.key}>
                <div className="risk-component-head">
                  <span>{component.label}</span>
                  <strong>{component.available ? `${component.value}/100` : '—'}</strong>
                </div>
                <div className="risk-track">
                  <span style={{ width: `${Math.max(2, component.value)}%`, background: risk.color }} />
                </div>
                <div className="risk-component-foot">
                  <span>{component.detail}</span>
                  <em>Weight {Math.round(component.weight * 100)}%</em>
                </div>
              </div>
            ))}
          </div>

          <p className="risk-method">{risk.method}</p>
        </section>
      </div>

      <section className="card">
        <div className="card-head">
          <div>
            <h2 className="card-title">Computed advisories</h2>
            <p className="card-subtitle">
              {alerts.length
                ? `${alerts.length} advisor${alerts.length === 1 ? 'y' : 'ies'} generated from current thresholds`
                : 'Nothing crosses the current thresholds'}
            </p>
          </div>
          <DataBadge status="estimated" label="Not official" />
        </div>

        {alerts.length ? (
          <div className="alert-list">
            {alerts.map((alert) => (
              <AlertCard alert={alert} key={alert.id} />
            ))}
          </div>
        ) : (
          <EmptyState
            icon={ShieldCheck}
            title="No advisories right now"
            description="Today's forecast does not cross the configured rain, heat, wind, UV or air-quality thresholds. You can adjust the thresholds in Settings."
          />
        )}
      </section>

      <ChartCard
        title="7-day risk outlook"
        subtitle="The same transparent weighting applied to each day's forecast"
        badge={<DataBadge status="estimated" />}
        className="span-2"
        height={280}
      >
        <ResponsiveContainer width="100%" height="100%">
          <BarChart data={daily} margin={{ top: 16, right: 10, left: -22, bottom: 0 }}>
            <CartesianGrid strokeDasharray="3 6" vertical={false} stroke="var(--border)" />
            <XAxis
              dataKey="label"
              tick={{ fontSize: 11, fill: 'var(--text-soft)' }}
              axisLine={false}
              tickLine={false}
            />
            <YAxis
              domain={[0, 100]}
              tick={{ fontSize: 11, fill: 'var(--text-soft)' }}
              axisLine={false}
              tickLine={false}
              width={42}
            />
            <Tooltip content={<RiskTooltip />} cursor={{ fill: 'var(--surface-2)' }} />
            <ReferenceLine y={50} stroke="var(--border-strong)" strokeDasharray="4 4" />
            <Bar dataKey="score" radius={[5, 5, 0, 0]} barSize={30}>
              {daily.map((day) => (
                <Cell key={day.date} fill={day.color} />
              ))}
            </Bar>
          </BarChart>
        </ResponsiveContainer>
      </ChartCard>

      <section className="card risk-scale-card">
        <div className="card-head">
          <div>
            <h2 className="card-title">How the score is built</h2>
            <p className="card-subtitle">Documented weights, no hidden model</p>
          </div>
          <Info size={18} aria-hidden="true" />
        </div>
        <div className="risk-scale-grid">
          {[
            { range: '0–25', label: 'Low', copy: 'Conditions are generally favourable.' },
            { range: '26–50', label: 'Moderate', copy: 'Sensitive people should take sensible precautions.' },
            { range: '51–75', label: 'High', copy: 'Plan outdoor activity carefully and reduce peak exposure.' },
            { range: '76–100', label: 'Severe', copy: 'Limit outdoor exposure and follow official health advisories.' },
          ].map((item) => (
            <div className="risk-scale-item" key={item.label}>
              <span>{item.range}</span>
              <strong>{item.label}</strong>
              <p>{item.copy}</p>
            </div>
          ))}
        </div>
        <p className="risk-method">{risk.disclaimer}</p>
        <Link to="/app/settings" className="text-link">
          Adjust the thresholds used here <ArrowRight size={13} />
        </Link>
      </section>

      <SourceNote
        className="page-source-note"
        sources={[
          { name: 'IMD rainfall and heat criteria', url: 'https://mausam.imd.gov.in/' },
          { name: 'CPCB AQI categories', url: 'https://cpcb.nic.in/national-air-quality-index/' },
          { name: 'Open-Meteo forecast', url: 'https://open-meteo.com/' },
        ]}
      >
        Thresholds are public reference values, but the combination is WeatherGPT's own heuristic.
        A low score does not guarantee safety, and a high score is not an official emergency
        declaration.
      </SourceNote>
    </div>
  );
}
